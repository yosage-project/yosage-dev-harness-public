#!/usr/bin/env bash
# harness/lib/worktree-root.sh — 割り当て作業ツリー(isolation:"worktree" が作る、または
# cross-repo 構成でメインが明示的に `git worktree add` する作業ツリー)置き場の単一ホーム。
#
# 背景: 遮断の判定(hooks/guard.sh の worktree 隔離セクション)と掃除の走査既定値
# (lib/epic-cleanup.sh)は、consumer の `.claude/` からの同じ相対パスを指す必要がある。
# 以前はこのリテラルを各ファイルが個別に持っており(パターン一致・sed による切り詰めも
# それぞれ独立に再実装)、揃っていることを誰も保証していなかった。ここへ集約する。
#
# 判定の意味論(発火条件・射程)そのものはここでは変えない。参照先を1箇所にまとめるだけ。
set -uo pipefail

# consumer の `.claude/` からの相対パス。guard.sh のパターン一致・epic-cleanup.sh の走査既定値の
# 両方がこの値を参照する。ここを変えれば両方が追随する(集約の効果はここが唯一の家であることに
# 依存する。個別に同じ値を書き足すと同じ drift が再発する)。
#
# --- この値は外部の挙動への依存であり、このコードベースが定めた契約ではない ---
# `.claude/worktrees` は実行環境(Claude Code 本体)が isolation:"worktree" を honor する際に
# 実際にどこへ worktree を作るか、という**観測事実**であって、このリポジトリが強制している
# 配置ではない。実行環境が置き場を変えれば、この定数は静かに実態と食い違う。
#
# 食い違ったときに何が起きるか: wt_assigned_root() は該当 cwd に対して非ゼロで返るようになり、
# 呼び出し側(hooks/guard.sh の worktree 隔離判定・lib/epic-cleanup.sh の走査)は
# **エラーを出さずに no-op へ落ちる(fail-open)**。既存の判定はすべて「配下でなければ何もしない
# (通常のメインセッションを誤爆させないための意図的な設計)」を前提にしているため、この食い違いを
# 内側から検出する仕組みは無い。
#
# 検査で受けなかった理由: この依存は実行環境(Claude Code 本体)の実際の配置動作そのものであり、
# このリポジトリのテストスイート(test/run.sh)が使う合成 fixture のディレクトリ構造は、この定数と
# 同じ形を最初から前提にして組み立てるため、実行環境側が形を変えても fixture 側は追随せず、
# 検査は常に緑のまま残る(=何も固定していない)。実行環境を実際に起動してこの配置を観測する
# 手段(隔離されたセッションを新たに起動して副作用を確認する等)も検討したが、入れ子の実行環境
# セッションが親セッションの認証情報を継承しない制約があり、直接検証はできなかった。
# 一方で、この値が今も実態と合っていることは、**この値を消費している側を実際に動かした結果**
# (隔離されたセッション自身の作業ディレクトリ・`git worktree list` が返す実際の worktree の置き場)
# から確認できる——これは合成 fixture ではなく実行環境が実際に作った状態そのものを見る観測であり、
# 新たなセッションを起動する必要が無い。この定数を変更する際は、その確認を先に行うこと。
#
# 別の信号(遮断が発火しなかった場合の分類だけを記録する等)も検討したが採らなかった。この経路は
# Edit/Write/Bash のあらゆる呼び出しで発火する(遮断そのものより遥かに高頻度)ため、判定のたびに
# 記録すると常時のオーバーヘッドになる。加えて「配下でない」という記録単体では、それが通常の
# メインセッション(想定どおり no-op)なのか、隔離が要求されたのに配置が変わったのかを区別できず、
# 記録が増えても解釈できる材料にならない。
#
# --- 別種の依存: このファイル自身が読み込まれない場合 ---
# 上記は「値の中身(.claude/worktrees)が実態と合っているか」という依存だが、もう1つ別の依存が
# ある——「このファイル自身が guard.sh から source される」ことへの依存。呼び出し側
# (hooks/guard.sh 冒頭)はこのファイルを best-effort で source しており、**このファイルが
# 欠落している/読み取れない場合も**、上記と同じ fail-open(判定が無音で無効化される)が起きる。
# 詳細な非対称(欠落=完全に無音・権限不可=bash 自身が stderr へ Permission denied を出す)は
# hooks/guard.sh 冒頭のコメントに書いた。
#
# こちらは上記(実行環境の配置)とは違う結論を採った——**検査で受けている**(test/run.sh に、
# このファイルを欠落/権限不可にした状態で guard.sh が実際に fail-open することを固定する
# 回帰テストがある)。理由: 上記の配置依存は実行環境(Claude Code 本体)というこのリポジトリの
# 外側の挙動そのものであり、合成 fixture では原理的に固定できない(fixture 自身が前提を
# 埋め込むだけになる)。一方この「ファイル自身が読めるか」という依存は、guard.sh 自身の
# source ロジックという**このリポジトリの内側**の挙動であり、実際にファイルを削除・
# chmod するだけで本物の失敗を再現でき、fixture が外部の挙動を代弁する必要が無い。
# 同じ3択(検査で受ける/前提記録に留める/別の信号を持つ)でも、対象の性質が違えば結論が
# 変わってよい、という判断をここで実際に適用した。
WT_ASSIGNED_ROOT_RELPATH=".claude/worktrees"

# hook 入力の .cwd(第1引数)が割り当て作業ツリー($WT_ASSIGNED_ROOT_RELPATH/<id>)配下かどうかを
# 判定する。配下なら割り当てルート(.../<id> まで切り詰めた絶対パス)を標準出力へ返し 0 で終了する。
# 配下でなければ何も出さず非ゼロで終了する(通常のメインセッション等は no-op)。
wt_assigned_root() {
  local cwd="${1:-}"
  local relpath_re="${WT_ASSIGNED_ROOT_RELPATH//./\\.}"
  case "$cwd" in
    */"$WT_ASSIGNED_ROOT_RELPATH"/*)
      printf '%s' "$cwd" | sed -E "s#(.*/${relpath_re}/[^/]+).*#\\1#"
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}
